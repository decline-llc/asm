def test_broker_proxy_denies_foreign_connect_without_asking_the_coordinator(monkeypatch):
    module = broker_module("asm_test_broker_connect")
    module.SPEC = {"timeout": 2, "host": "authorized.invalid"}
    seen = []
    monkeypatch.setattr(module, "emit", lambda frame: seen.append(frame))
    server = ThreadingHTTPServer(("127.0.0.1", 0), module.Proxy)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        with httpx.Client(proxy="http://127.0.0.1:" + str(server.server_port), trust_env=False) as client:
            with pytest.raises(httpx.HTTPError):
                client.get("https://cdn.example.invalid/lib.js")
        assert seen == []
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=2)


def test_scope_blocks_reach_the_run_record(tmp_path):
    ctx = Context(tmp_path, "web_visit", "httpx")
    ctx.records = []
    ctx.run["directory"] = str(tmp_path)
    blocks = [{"url": "http://outside.invalid/lib.js", "reason": "outside_function_scope"}]
    parsed = external_tools.parse_http_result(ctx, {"exit_code": 0, "protocol_completed": True, "artifacts": {},
        "requests": [{"url": "http://localhost:8765/", "status": 200, "evidence_id": "raw-1"}], "scope_blocks": blocks})
    health = next(row for row in parsed["records"] if row.get("category") == "tool_health")
    assert health["scope_blocks"] == blocks


def test_brokered_request_reaches_in_scope_target_and_uses_the_broker_ledger(m5_fixture):  # noqa: F811
    _, server, base = m5_fixture
    captured = {}

    def adapter(parent):
        requests, errors = [], []
        reply = external_tools.broker_request(parent, {"id": "broker-1", "url": base + "/child",
                                                      "method": "GET"}, requests, errors)
        captured.update(reply=reply, requests=requests, errors=errors)
        return result(parent, status="completed")

    wb, run, _ = run_capability(m5_fixture, "web_visit", {"max_requests_per_host": 4},
                                adapters={"web_visit": adapter})
    assert base64.b64decode(captured["reply"]["body_base64"]).startswith(b'<a href="/#again">')
    assert captured["reply"]["status"] == 200 and captured["errors"] == []
    assert [row["path"] for row in server.requests] == ["/child"]
    assert captured["requests"][0]["url"] == base + "/child"
    started = [row["data"] for row in wb.store.events(run["run_id"])
               if row["kind"] == "physical_request_started"]
    assert [event["transport"] for event in started] == ["isolated_http_broker"]
    assert started[0]["method"] == "GET"


def test_brokered_out_of_scope_subresource_is_denied_before_any_transport(m5_fixture):  # noqa: F811
    _, server, base = m5_fixture
    captured = {}

    def adapter(parent):
        requests, errors = [], []
        reply = external_tools.broker_request(parent, {"id": "broker-2", "url": "http://outside.invalid/lib.js",
                                                      "method": "GET"}, requests, errors)
        captured.update(reply=reply, requests=requests, errors=errors)
        return result(parent, status="completed", reason="fixture_scope_block_check")

    wb, run, _ = run_capability(m5_fixture, "web_visit", {}, adapters={"web_visit": adapter})
    assert captured["reply"]["status"] == 403 and captured["reply"]["body_base64"] == ""
    assert captured["requests"] == []
    assert captured["errors"] == [{"url": "http://outside.invalid/lib.js", "reason": "outside_function_scope"}]
    # The loopback fixture was never contacted and no non-local name was resolved.
    assert server.requests == []
    events = wb.store.events(run["run_id"])
    assert [row["kind"] for row in events if row["kind"].startswith("physical_request")] == []


def test_brokered_request_budget_exhaustion_fails_the_job(m5_fixture):  # noqa: F811
    _, server, base = m5_fixture
    observed = {}

    def adapter(parent):
        requests, errors = [], []
        external_tools.broker_request(parent, {"id": "broker-3", "url": base + "/open", "method": "GET"},
                                      requests, errors)
        with pytest.raises(PolicyDenied, match="http_request_budget_exhausted"):
            external_tools.broker_request(parent, {"id": "broker-4", "url": base + "/open?again", "method": "GET"},
                                          requests, errors)
        observed["requests"] = requests
        return result(parent, status="partial", reason="fixture_budget_propagation")

    wb, run, _ = run_capability(m5_fixture, "web_visit", {"max_requests_per_host": 1},
                                adapters={"web_visit": adapter})
    assert [row["path"] for row in server.requests] == ["/open"]
    assert len(observed["requests"]) == 1
    kinds = [row["kind"] for row in wb.store.events(run["run_id"]) if row["kind"].startswith("physical_request")]
    assert kinds == ["physical_request_started", "physical_request_blocked"]