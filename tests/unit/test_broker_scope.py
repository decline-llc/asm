"""Scope-control contract for the isolated HTTP broker.

Every URL, redirect hop and browser subresource generated by a WSL HTTP tool is
relayed to ExecutionContext.http, which owns the authorization scope, the durable
per-host request budget and the receipts. These tests pin that contract: an
out-of-scope subresource is answered with 403 and costs no transport, while a
revoked window or an exhausted budget fails the job instead of looking like a
remote 4xx.
"""
import base64
from http.server import ThreadingHTTPServer
import importlib.util
from pathlib import Path
import re
import threading

import httpx
import pytest

from asm import external_tools
from asm.policy import PolicyDenied
from asm.workbench_tools import result
from tests.unit.test_active_tools import Context  # noqa: F401 - shared minimal context
from tests.unit.test_workbench_tools_m5 import m5_fixture, run_capability  # noqa: F401


def broker_module(name):
    source = Path(__file__).resolve().parents[2] / "tools/http_tool_runner.py"
    spec = importlib.util.spec_from_file_location(name, source)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Coordinator:
    """Stand-in for ExecutionContext.http with the same denial vocabulary."""

    def __init__(self, denial=""):
        self.params = {"max_response_bytes": 2048}
        self.last_evidence_id = "evidence-1"
        self.denial = denial
        self.calls = []

    def http(self, url, **kwargs):
        self.calls.append((url, kwargs))
        if self.denial:
            raise PolicyDenied(self.denial)
        return {"status": 200, "headers": {"content-type": "text/html"}, "body": "<html>fixture</html>"}


@pytest.mark.parametrize("target,inside,outside", [
    ("https://app.example.invalid/",
     ["https://app.example.invalid", "https://app.example.invalid/x", "https://app.example.invalid/?q=1"],
     ["http://app.example.invalid/", "https://other.example.invalid/",
      "https://app.example.invalid.evil.invalid/", "https://app.example.invalid:8443/"]),
    ("https://app.example.invalid:8443/base",
     ["https://app.example.invalid:8443/base/x", "https://app.example.invalid:8443/"],
     ["https://app.example.invalid/", "https://app.example.invalid:8443.evil.invalid/",
      "https://app.example.invalid:8444/base"]),
    ("http://127.0.0.1:8765/",
     ["http://127.0.0.1:8765/a", "http://127.0.0.1:8765/"],
     ["http://127.0.0.1:8766/a", "https://127.0.0.1:8765/a", "http://127.0.0.10:8765/a"]),
])
def test_crawl_scope_is_exact_origin_only(target, inside, outside):
    pattern = external_tools.crawl_scope(target)
    for url in inside:
        assert re.search(pattern, url), url
    for url in outside:
        assert not re.search(pattern, url), url


@pytest.mark.parametrize("method", ["GET", "HEAD"])
def test_broker_request_relays_in_scope_request_with_receipt(method):
    ctx = Coordinator()
    requests, errors = [], []
    frame = {"id": "frame-1", "url": "https://app.example.invalid/page", "method": method,
             "headers": {"accept": "text/html"}}
    reply = external_tools.broker_request(ctx, frame, requests, errors)
    assert reply["id"] == "frame-1" and reply["status"] == 200
    assert base64.b64decode(reply["body_base64"]) == b"<html>fixture</html>"
    url, options = ctx.calls[0]
    assert url == frame["url"] and options["method"] == method
    assert options["follow_redirects"] is False
    assert options["transport"] == "isolated_http_broker"
    assert options["request_headers"] == {"accept": "text/html"}
    assert options["max_response_bytes"] == 2048
    assert requests == [{"url": frame["url"], "status": 200, "evidence_id": "evidence-1"}]
    assert errors == []


def test_broker_request_answers_out_of_scope_url_with_403_and_no_observation():
    ctx = Coordinator("web_visit: outside_function_scope")
    requests, errors = [], []
    reply = external_tools.broker_request(ctx, {"id": "frame-2", "url": "http://outside.invalid/lib.js",
                                                "method": "GET"}, requests, errors)
    assert reply == {"id": "frame-2", "status": 403, "headers": {}, "body_base64": ""}
    assert requests == []
    assert errors == [{"url": "http://outside.invalid/lib.js", "reason": "outside_function_scope"}]


@pytest.mark.parametrize("denial", ["http_request_budget_exhausted", "authorization_revoked"])
def test_broker_request_fails_job_on_budget_or_revocation(denial):
    ctx = Coordinator(denial)
    with pytest.raises(PolicyDenied, match=denial):
        external_tools.broker_request(ctx, {"id": "frame-3", "url": "https://app.example.invalid/",
                                            "method": "GET"}, [], [])


@pytest.mark.parametrize("frame", [
    {"id": "frame-4", "url": "https://app.example.invalid/", "method": "POST"},
    {"id": "frame-5", "url": "https://app.example.invalid/", "method": "DELETE"},
    {"id": "frame-6", "url": "ftp://app.example.invalid/", "method": "GET"},
    {"id": "frame-7", "url": "file:///etc/passwd", "method": "GET"},
])
def test_broker_request_refuses_other_methods_and_schemes(frame):
    ctx = Coordinator()
    with pytest.raises(ValueError, match="Unsupported broker request"):
        external_tools.broker_request(ctx, frame, [], [])
    assert ctx.calls == []


